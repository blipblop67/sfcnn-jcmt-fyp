"""Write a manifest for every GBS DR3 850 um map found in data/real/.

Each map is assigned to a parent cloud (used for leave-one-cloud-out testing) and an
approximate distance (used only when cutout.size_pc is set). Distances are rounded
literature values; check and cite them properly before quoting them in the report:
  Ophiuchus ~140 pc, Corona Australis ~150 pc, Lupus ~155 pc, Cepheus L1228 ~200 pc,
  Cepheus L1251/South ~300 pc, Perseus ~300 pc, Serpens/Aquila ~436 pc,
  Auriga-California ~450 pc, IC 5146 ~750 pc (poorly constrained, 600-950 pc in the literature).

Usage: python scripts/make_gbs_manifest.py [data/real] [configs/gbs_manifest.yaml]
"""
import sys
from pathlib import Path

import yaml

CLOUDS = [  # (filename prefix, cloud, distance_pc)
    ("PerseusWest", "Perseus", 300), ("PerseusIC348", "Perseus", 300),
    ("OphScoMain", "Ophiuchus", 140), ("OphScoN2", "Ophiuchus", 140),
    ("OphScoN3", "Ophiuchus", 140), ("OphScoN6", "Ophiuchus", 140),
    ("SerpensMain", "SerpensAquila", 436), ("SerpensE", "SerpensAquila", 436),
    ("SerpensN", "SerpensAquila", 436), ("SerpensMWC297", "SerpensAquila", 436),
    ("Aquila", "SerpensAquila", 436),
    ("AurigaCentral", "Auriga", 450), ("AurigaLkHa101", "Auriga", 450), ("AurigaNorth", "Auriga", 450),
    ("CepheusL1228", "Cepheus", 200), ("CepheusL1251", "Cepheus", 300), ("CepheusSouth", "Cepheus", 300),
    ("IC5146", "IC5146", 750), ("CrA", "CrA", 150), ("Lupus", "Lupus", 155),
]


def main(data_dir="data/real", out="configs/gbs_manifest.yaml", yso="gbs_ysos_all.csv"):
    data_dir, out = Path(data_dir), Path(out)
    rel = Path("..") / data_dir  # manifest lives in configs/
    regions = []
    for prefix, cloud, dist in CLOUDS:
        maps = sorted(data_dir.glob(f"{prefix}_*_850_DR3_ext_HK.fits.gz"))
        if not maps:
            print(f"skip {prefix}: no 850 um map")
            continue
        r = {"name": prefix, "cloud": cloud, "distance_pc": dist,
             "map": str(rel / maps[0].name).replace("\\", "/"),
             "yso_catalog": str(rel / yso).replace("\\", "/")}
        m450 = sorted(data_dir.glob(f"{prefix}_*_450_DR3_ext_HK.fits.gz"))
        if m450:
            r["map_450"] = str(rel / m450[0].name).replace("\\", "/")
        regions.append(r)
    out.write_text("# Generated by scripts/make_gbs_manifest.py\n"
                   + yaml.safe_dump({"regions": regions}, sort_keys=False), encoding="utf-8")
    print(f"{len(regions)} regions -> {out}")


if __name__ == "__main__":
    main(*sys.argv[1:])
